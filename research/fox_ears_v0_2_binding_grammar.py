class CueExtractor:
    """
    Extracts continuity evidence between consecutive EAR MEASUREMENTS.

    It deliberately does not decide which cue should dominate.
    """

    def spectral(self, a: EarFrame, b: EarFrame) -> CueEvidence:
        va = []
        vb = []
        for band in BANDS_HZ:
            va += [a.left_bands.get(band, 0.0), a.right_bands.get(band, 0.0)]
            vb += [b.left_bands.get(band, 0.0), b.right_bands.get(band, 0.0)]
        sim = cosine_similarity(va, vb)
        return CueEvidence(
            "spectral",
            f"t={a.t_ms}",
            f"t={b.t_ms}",
            sim,
            1.0 - sim,
            {"cosine_similarity": round(sim, 6)},
        )

    def temporal_contour(self, a: EarFrame, b: EarFrame) -> CueEvidence:
        # Gross amplitude contour continuity: compare total bilateral level change.
        total_a = (a.left_level + a.right_level) / 2.0
        total_b = (b.left_level + b.right_level) / 2.0
        sim = normalized_similarity(total_a, total_b, scale=0.12)
        return CueEvidence(
            "temporal_contour",
            f"t={a.t_ms}",
            f"t={b.t_ms}",
            sim,
            1.0 - sim,
            {
                "mean_level_a": round(total_a, 6),
                "mean_level_b": round(total_b, 6),
                "absolute_change": round(abs(total_b-total_a), 6),
            },
        )

    def onset_offset(self, a: EarFrame, b: EarFrame) -> CueEvidence:
        silence_a = a.left_level < 0.005 and a.right_level < 0.005
        silence_b = b.left_level < 0.005 and b.right_level < 0.005
        new_onset = max(b.left_onset, b.right_onset)
        if silence_a != silence_b:
            continuity = 0.15
        elif new_onset >= 0.12 and not silence_b:
            continuity = 0.25
        else:
            continuity = 0.95
        return CueEvidence(
            "onset_offset",
            f"t={a.t_ms}",
            f"t={b.t_ms}",
            continuity,
            1.0 - continuity,
            {
                "silence_a": silence_a,
                "silence_b": silence_b,
                "new_onset_b": round(new_onset, 6),
            },
        )

    def binaural_trajectory(self, a: EarFrame, b: EarFrame) -> CueEvidence:
        da = a.left_level - a.right_level
        db = b.left_level - b.right_level
        level_sim = normalized_similarity(da, db, scale=0.08)

        if a.itd_ms_r_minus_l is not None and b.itd_ms_r_minus_l is not None:
            itd_sim = normalized_similarity(a.itd_ms_r_minus_l, b.itd_ms_r_minus_l, scale=0.5)
            sim = (level_sim + itd_sim) / 2.0
        else:
            itd_sim = None
            sim = level_sim

        return CueEvidence(
            "binaural_trajectory",
            f"t={a.t_ms}",
            f"t={b.t_ms}",
            sim,
            1.0 - sim,
            {
                "level_delta_a": round(da, 6),
                "level_delta_b": round(db, 6),
                "itd_similarity": None if itd_sim is None else round(itd_sim, 6),
            },
        )

    def interval(self, a: EarFrame, b: EarFrame) -> CueConflictLedger:
        cues = [
            self.spectral(a,b),
            self.temporal_contour(a,b),
            self.onset_offset(a,b),
            self.binaural_trajectory(a,b),
        ]

        # "Strong continuity" vs "strong discontinuity" contradiction.
        supporting = [c.cue_type for c in cues if c.continuity >= 0.75]
        opposing = [c.cue_type for c in cues if c.continuity <= 0.35]
        contradictions = [(s,o) for s in supporting for o in opposing]
        return CueConflictLedger(a.t_ms, b.t_ms, cues, contradictions)

    def series(self, frames: Sequence[EarFrame]) -> List[CueConflictLedger]:
        return [self.interval(a,b) for a,b in zip(frames, frames[1:])]


