#!/usr/bin/env python3
"""
FOX EARS v0.2 — BINDING GRAMMAR
================================

Purpose
-------
Replace the v0.1 "pre-bound anonymous object" path with an inspectable evidence-first
auditory binding architecture.

Pipeline
--------
WORLD TRUTH
    -> EAR MEASUREMENT (L/R only)
    -> CUE EXTRACTION
        spectral continuity
        temporal contour continuity
        onset/offset continuity
        binaural trajectory continuity
    -> CUE CONFLICT LEDGER
    -> BINDING HYPOTHESES
        candidate / preferred / unresolved
    -> BLIND RECEIPT
    -> WINONA TRANSDUCTION

Rules
-----
- WORLD TRUTH never appears in the blind receipt.
- No source IDs, object IDs, semantic source labels, or derived "left/right/moving" words
  appear in blind calibration data.
- Cue weights are NOT hard-coded as a perceptual hierarchy.
- Competing histories are first-class.
- Masking persistence is a confidence-bearing hypothesis, never simulator truth.
- No AUDITORY_FEEL field.
- Calibration 003 is generated by the runtime.

This is a toy auditory mechanics/calibration system, not a validated psychoacoustic or
neuroscience model.
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Dict, List, Tuple, Optional, Sequence, Any
import argparse
import json
import math
import unittest


VERSION = "fox-ears-0.2"
BANDS_HZ = (500, 1000, 2000, 4000)
CUE_TYPES = ("spectral", "temporal_contour", "onset_offset", "binaural_trajectory")


def clamp(x: float, lo: float = 0.0, hi: float = 1.0) -> float:
    return max(lo, min(hi, float(x)))


def cosine_similarity(a: Sequence[float], b: Sequence[float]) -> float:
    na = math.sqrt(sum(x*x for x in a))
    nb = math.sqrt(sum(x*x for x in b))
    if na == 0.0 and nb == 0.0:
        return 1.0
    if na == 0.0 or nb == 0.0:
        return 0.0
    return clamp(sum(x*y for x, y in zip(a, b)) / (na * nb))


def normalized_similarity(a: float, b: float, scale: float = 1.0) -> float:
    return clamp(1.0 - abs(a - b) / max(scale, 1e-9))


