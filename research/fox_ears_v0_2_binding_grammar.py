VERSION = "fox-ears-0.2"
BANDS_HZ = (500, 1000, 2000, 4000)
CUE_TYPES = ("spectral", "temporal_contour", "onset_offset", "binaural_trajectory")
AVAILABILITY = ("AVAILABLE", "UNAVAILABLE")

# P0 (2026-11-15) cue-extractor constants. Frame generation is untouched, so
# the Calibration 003 challenge-fixture pack stays byte-identical.
SILENCE_LEVEL = 0.005        # both ears below this = silent frame (same rule onset_offset already used)
BAND_EPS = 1e-6              # a band "has energy" above this
ILD_SCALE_DB = 4.0           # interaural level change (dB) that reads as a full spatial break
ITD_SCALE_MS = 0.5           # interaural time change (ms) that reads as a full spatial break
CONTOUR_PATTERN_DB = 4.0     # per-band envelope deviation from its own recent pattern (dB) = full break
BREAK_T = 0.45               # a cue interval at or below this continuity is a local break
STRONG_CONT = 0.75           # at or above this a cue strongly argues for continuity
BLIP_WEIGHT = 0.30           # break events weaker than this (after persistence) are logged as BLIPs


def clamp(x: float, lo: float = 0.0, hi: float = 1.0) -> float:
    return max(lo, min(hi, float(x)))


def cosine_similarity(a: Sequence[float], b: Sequence[float]) -> float:
    na = math.sqrt(sum(x*x for x in a))
    nb = math.sqrt(sum(x*x for x in b))
    if na == 0.0 and nb == 0.0:
        return 1.0
    if na == 0.0 or nb == 0.0:
        return 0.0
    return clamp(sum(x*y for x, y in zip(a, b)) / (na * nb))


def normalized_similarity(a: float, b: float, scale: float = 1.0) -> float:
    return clamp(1.0 - abs(a - b) / max(scale, 1e-9))


