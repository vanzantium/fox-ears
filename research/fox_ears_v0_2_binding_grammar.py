"""
FOX EARS v0.2 — BINDING GRAMMAR
================================

Purpose
-------
Replace the v0.1 "pre-bound anonymous object" path with an inspectable evidence-first
auditory binding architecture.

Pipeline
--------
WORLD TRUTH
    -> EAR MEASUREMENT (L/R only)
    -> CUE EXTRACTION
        spectral continuity
        temporal contour continuity
        onset/offset continuity
        binaural trajectory continuity
    -> CUE CONFLICT LEDGER
    -> BINDING HYPOTHESES
        candidate / preferred / unresolved
    -> BLIND RECEIPT
    -> WINONA TRANSDUCTION

Rules
-----
- WORLD TRUTH never appears in the blind receipt.
- No source IDs, object IDs, semantic source labels, or derived "left/right/moving" words
  appear in blind calibration data.
- Cue weights are NOT hard-coded as a perceptual hierarchy.
- Competing histories are first-class.
- Masking persistence is a confidence-bearing hypothesis, never simulator truth.
- No AUDITORY_FEEL field.
- Calibration 003 is generated by the runtime. Its manipulation map is visible in
  this source, so it is a CHALLENGE FIXTURE / calibration game, not a blind test
  (Arch review 2026-11-15; Taylor's ruling: no blind-test ceremony). "Blind
  receipt" below still means a measurement-only receipt. Readings are SOFT until
  checked and SOLID once independently supported.

P0 2026-11-15: local break events drive SAME / SPLIT / UNRESOLVED; silent frames
make spectral continuity UNAVAILABLE; spatial continuity uses ILD (dB) and ITD as
separate measures. Frame generation is unchanged and the Cal 003 pack is pinned by
sha256 in the tests.

This is a toy auditory mechanics/calibration system, not a validated psychoacoustic or
neuroscience model.
"""

