class Calibration003Generator:
    TIMES = (0,100,200,300,400,500,650,800,1000)

    @staticmethod
    def _lr(amp: float, x: float) -> Tuple[float,float]:
        return amp*(1-.20*x), amp*(1+.20*x)

    @staticmethod
    def _mk_frame(t: int, streams: List[Dict[str, float]], itd=None) -> EarFrame:
        LB={b:0.0 for b in BANDS_HZ}; RB={b:0.0 for b in BANDS_HZ}
        onset=0.0
        for s in streams:
            LB[int(s["band"])] = float(s["L"])
            RB[int(s["band"])] = float(s["R"])
            onset=max(onset,float(s.get("onset",0.0)))
        L=0.1*math.sqrt(sum(v*v for v in LB.values()))
        R=0.1*math.sqrt(sum(v*v for v in RB.values()))
        return EarFrame(t,L,R,LB,RB,onset,onset,itd)

    def build(self) -> Tuple[Dict[str,List[EarFrame]], Dict[str,WorldTruthEvent]]:
        events={}
        truth={}
        T=self.TIMES

        # H: spectrum breaks, others broadly continuous
        f=[]
        for i,t in enumerate(T):
            x=-.6+1.2*i/(len(T)-1); amp=.68+.08*math.sin(i*.7); band=1000 if t<500 else 4000
            L,R=self._lr(amp,x)
            f.append(self._mk_frame(t,[{"band":band,"L":L,"R":R,"onset":.2 if i==0 else 0}]))
        events["H"]=f
        truth["H"]=WorldTruthEvent("H","spectral continuity violation",["one simulator history continues across spectral change"])

        # N: true gap/re-onset
        f=[]
        for i,t in enumerate(T):
            if t==500:
                f.append(self._mk_frame(t,[])); continue
            x=-.5+1.0*i/(len(T)-1); amp=.70+.06*math.sin(i*.8); L,R=self._lr(amp,x)
            f.append(self._mk_frame(t,[{"band":2000,"L":L,"R":R,"onset":.24 if i==0 else (.22 if t==650 else 0)}]))
        events["N"]=f
        truth["N"]=WorldTruthEvent("N","onset/offset continuity violation",["simulator history resumes after gap"],"perceptual same-object continuation is not guaranteed")

        # C: spatial discontinuity
        f=[]
        for i,t in enumerate(T):
            amp=.70+.05*math.sin(i*.75); x=-.75 if t<500 else .75; L,R=self._lr(amp,x)
            f.append(self._mk_frame(t,[{"band":1000,"L":L,"R":R,"onset":.2 if i==0 else 0}]))
        events["C"]=f
        truth["C"]=WorldTruthEvent("C","binaural trajectory discontinuity",["one simulator source teleports spatially"])

        # T: amplitude-contour phase change, spectrum + trajectory continuous
        f=[]
        for i,t in enumerate(T):
            x=-.6+1.2*i/(len(T)-1)
            amp=.82 if i%2==0 else .48
            if t>=500: amp=.48 if i%2==0 else .82
            L,R=self._lr(amp,x)
            f.append(self._mk_frame(t,[{"band":4000,"L":L,"R":R,"onset":.2 if i==0 else 0}]))
        events["T"]=f
        truth["T"]=WorldTruthEvent("T","temporal contour continuity violation",["one simulator source continues"])

        # Q: crossing; spectral continuity vs exchanged amplitude contour
        f=[]
        for i,t in enumerate(T):
            frac=i/(len(T)-1); x1=-1+2*frac; x2=1-2*frac
            a=.82 if i%2==0 else .48; b=.48 if i%2==0 else .82
            if t>=500: a,b=b,a
            L1,R1=self._lr(a,x1); L2,R2=self._lr(b,x2)
            f.append(self._mk_frame(t,[
                {"band":1000,"L":L1,"R":R1,"onset":.2 if i==0 else 0},
                {"band":4000,"L":L2,"R":R2,"onset":.2 if i==0 else 0},
            ]))
        events["Q"]=f
        truth["Q"]=WorldTruthEvent("Q","cue conflict at crossing",[
            "spectral trajectories support straight-through histories",
            "amplitude contour exchange supports alternative identity assignment",
        ],"intentionally underdetermined perceptually")

        # W: crossing plus true gap/re-onset
        f=[]
        for i,t in enumerate(T):
            if t==500:
                f.append(self._mk_frame(t,[])); continue
            frac=i/(len(T)-1); x1=-1+2*frac; x2=1-2*frac
            L1,R1=self._lr(.72,x1); L2,R2=self._lr(.58,x2)
            re=.24 if t==650 else 0.0
            f.append(self._mk_frame(t,[
                {"band":1000,"L":L1,"R":R1,"onset":.2 if i==0 else re},
                {"band":4000,"L":L2,"R":R2,"onset":.2 if i==0 else re},
            ]))
        events["W"]=f
        truth["W"]=WorldTruthEvent("W","spectrum/spatial continuation vs offset/re-onset split evidence",[
            "simulator trajectories continue across gap",
            "perceptual histories may split because sensory continuity breaks",
        ])

        return events, truth

    def pack(self) -> Tuple[Dict[str,Any], Dict[str,Any], Dict[str,Any]]:
        events, truth = self.build()
        runtime=FoxEarsBindingGrammar()

        blind={
            "schema":"fox-ears-calibration-003-blind",
            "version":VERSION,
            "constraints":{
                "hidden_state_included":False,
                "source_identifiers_included":False,
                "object_identifiers_included":False,
                "derived_spatial_words_included":False,
                "binding_hypotheses_included":False,
            },
            "events":{k:runtime.blind_receipt(k,v) for k,v in events.items()}
        }

        inspector={
            "schema":"fox-ears-calibration-003-inspector",
            "version":VERSION,
            "events":{k:runtime.analyze(k,v) for k,v in events.items()}
        }

        locked={
            "schema":"fox-ears-calibration-003-locked-key",
            "world_truth":{k:asdict(v) for k,v in truth.items()},
            "precommitted_scoring":{
                "field_fidelity":"Uses only supplied ear measurements.",
                "cue_separation":"Separates spectrum, temporal contour, onset/offset, and binaural trajectory.",
                "binding_independence":"Constructs object histories without IDs.",
                "conflict_preservation":"Keeps contradictory continuity cues alive.",
                "dominance_introspection":"Labels preferred binding as transduction, not measurement.",
                "alternative_world":"Preserves strongest competing history.",
                "uncertainty_calibration":"Confidence falls when binding is underdetermined.",
                "relational_memory":"Memory key preserves relation rather than exact labels/frequencies.",
                "semantic_restraint":"No real-world source identification required."
            },
            "warning":"Simulator world truth is not the perceptual answer key."
        }
        return blind, inspector, locked


