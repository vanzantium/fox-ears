@dataclass
class BreakEvent:
    """
    A first-class local break (Arch review 5A, 2026-11-15). One cue dropping at
    or below BREAK_T over one or more consecutive intervals.

    persistence: share of post-break checks where the cue stays broken against
                 the pre-break frame (the change held).
    recovery:    share of post-break checks where the cue is back to strong
                 continuity with the pre-break frame (there-and-back).
    weight:      break_strength x (0.35 + 0.65 x persistence); a one-frame blip
                 that recovers cannot carry the trial.
    verdict:     BLIP (weight < BLIP_WEIGHT, or no persistence and the cue
                 recovers), SPLIT (support >= conflict) or
                 UNRESOLVED (more cues argue for continuity than corroborate).
    """
    interval_ms: Tuple[int, int]
    cue: str
    break_strength: float
    persistence: float
    recovery: float
    supporting_cues: List[str]
    conflicting_cues: List[str]
    availability: Dict[str, str]
    weight: float
    verdict: str


class BreakEventDetector:
    def __init__(self, extractor: CueExtractor):
        self.extractor = extractor

    def detect(self, frames: Sequence[EarFrame], ledgers: Sequence[CueConflictLedger]) -> List[BreakEvent]:
        n = len(ledgers)
        table: List[Dict[str, CueEvidence]] = [{c.cue_type: c for c in l.cues} for l in ledgers]

        def avail(j: int, cue: str) -> bool:
            return 0 <= j < n and table[j][cue].availability == "AVAILABLE"

        def broken(j: int, cue: str) -> bool:
            return avail(j, cue) and table[j][cue].continuity <= BREAK_T

        events: List[BreakEvent] = []
        for cue in CUE_TYPES:
            j = 0
            while j < n:
                if not broken(j, cue):
                    j += 1
                    continue
                j0 = j
                while j + 1 < n and broken(j + 1, cue):
                    j += 1
                j1 = j
                j += 1
                pre, post = j0, j1 + 1
                strength = 1.0 - min(table[k][cue].continuity for k in range(j0, j1 + 1))
                checks = [self.extractor.bridge(cue, frames, pre, q) for q in (post, post + 1) if q < len(frames)]
                checks = [c for c in checks if c is not None]
                if checks:
                    persistence = sum(c <= BREAK_T for c in checks) / len(checks)
                    recovery = sum(c >= STRONG_CONT for c in checks) / len(checks)
                else:
                    persistence, recovery = 0.5, 0.0

                support, conflict = [], []
                availability = {}
                for other in CUE_TYPES:
                    span = range(j0, j1 + 1)
                    n_av = sum(avail(k, other) for k in span)
                    availability[other] = ("AVAILABLE" if n_av == len(span) else
                                           "UNAVAILABLE" if n_av == 0 else "PARTIAL")
                    if other == cue:
                        continue
                    if any(broken(k, other) for k in range(j0 - 1, j1 + 2)):
                        support.append(other)
                        continue
                    in_span_ok = all(table[k][other].continuity >= STRONG_CONT for k in span if avail(k, other))
                    b = self.extractor.bridge(other, frames, pre, post)
                    if n_av == 0:
                        # Cue silent in the span: it can still argue continuity across it.
                        if b is not None and b >= STRONG_CONT:
                            conflict.append(other)
                    elif in_span_ok and (b is None or b >= STRONG_CONT):
                        conflict.append(other)

                weight = strength * (0.35 + 0.65 * persistence)
                if weight < BLIP_WEIGHT or (persistence == 0.0 and recovery >= 0.5):
                    # Weak, or there-and-back: one noisy frame is logged, never decisive.
                    verdict = "BLIP"
                elif len(support) >= len(conflict):
                    verdict = "SPLIT"
                else:
                    verdict = "UNRESOLVED"
                events.append(BreakEvent(
                    (ledgers[j0].interval_a_ms, ledgers[j1].interval_b_ms), cue,
                    round(strength, 4), round(persistence, 4), round(recovery, 4),
                    support, conflict, availability, round(weight, 4), verdict))
        events.sort(key=lambda e: (e.interval_ms, e.cue))
        return events


class HypothesisBuilder:
    """
    Produces competing histories from local break events (P0 2026-11-15) without
    encoding a learned perceptual cue hierarchy.

    Confidence is evidence-balance, not "correctness".

    - H_SPLIT grows by noisy-OR over break events, each discounted by how many
      available cues argue continuity across it; BLIPs add almost nothing.
    - H_SAME is the mean continuity of available cues, capped by how well the
      other cues bridge the weakest real break event; UNAVAILABLE cues are
      excluded from both.
    - Any UNRESOLVED event (a real break that other cues contest) keeps both
      histories alive as unresolved, with confidences preserved as the lean.
    """

    def build(self, trial_id: str, ledgers: Sequence[CueConflictLedger],
              events: Optional[Sequence[BreakEvent]] = None) -> BindingLedger:
        if not ledgers:
            return BindingLedger(trial_id, [], [])
        events = list(events or [])

        cont_vals = {cue: [] for cue in CUE_TYPES}
        for ledger in ledgers:
            for c in ledger.cues:
                if c.availability == "AVAILABLE":
                    cont_vals[c.cue_type].append(c.continuity)
        live = [v for vals in cont_vals.values() for v in vals]
        base_same = clamp(sum(live) / len(live)) if live else 0.5

        real = [e for e in events if e.verdict != "BLIP"]
        blips = [e for e in events if e.verdict == "BLIP"]
        # Steady stretches must not outvote a decisive moment: SAME is capped by
        # how well the other available cues bridge the weakest real break.
        bridge = 1.0
        for e in real:
            others = [c for c, av in e.availability.items() if c != e.cue and av != "UNAVAILABLE"
                      or c in e.conflicting_cues]
            frac = len(e.conflicting_cues) / max(1, len(set(others)))
            bridge = min(bridge, 0.5 + 0.5 * frac)
        same_conf = clamp(base_same * bridge)
        miss = 1.0
        for e in real:
            s, k = len(e.supporting_cues), len(e.conflicting_cues)
            miss *= 1.0 - e.weight * (1 + s) / (1 + s + 0.5 * k)
        blip_miss = 1.0
        for e in blips:
            blip_miss *= 1.0 - 0.25 * e.weight
        split_conf = clamp(0.1 + 0.9 * (1.0 - miss * blip_miss))

        split_support = sorted({c for e in real for c in [e.cue, *e.supporting_cues]})
        split_oppose = sorted({c for e in real for c in e.conflicting_cues})
        same_support = sorted({cue for cue, vals in cont_vals.items()
                               if vals and sum(vals) / len(vals) >= 0.65 and cue not in split_support}
                              | set(split_oppose))
        same_oppose = split_support

        conflicts = [(l.interval_a_ms,l.interval_b_ms) for l in ledgers if l.has_conflict]

        if any(e.verdict == "UNRESOLVED" for e in real):
            statuses = ("unresolved","unresolved")
        elif real and abs(same_conf - split_conf) <= 0.15:
            statuses = ("unresolved","unresolved")
        elif same_conf > split_conf:
            statuses = ("preferred","candidate")
        elif split_conf > same_conf:
            statuses = ("candidate","preferred")
        else:
            statuses = ("unresolved","unresolved")

        hypotheses = [
            BindingHypothesis(
                f"{trial_id}:H_SAME",
                ["observations may belong to one continuing sound-thing"],
                same_support,
                same_oppose,
                same_conf,
                statuses[0],
                "continuity cues support one-history binding; conflicting cues remain explicit",
            ),
            BindingHypothesis(
                f"{trial_id}:H_SPLIT",
                ["a new sound-thing may appear at one or more discontinuities"],
                split_support,
                split_oppose,
                split_conf,
                statuses[1],
                "local break events support split/history-reset binding; continuity cues remain explicit",
            ),
        ]
        return BindingLedger(trial_id, hypotheses, conflicts)

    @staticmethod
    def resolution(binding: BindingLedger, events: Sequence[BreakEvent]) -> Dict[str, Any]:
        same, split = binding.hypotheses[0], binding.hypotheses[1]
        if same.status == "unresolved":
            state = "UNRESOLVED"
        elif same.status == "preferred":
            state = "SAME"
        else:
            state = "SPLIT"
        lean = "SAME" if same.confidence > split.confidence else "SPLIT" if split.confidence > same.confidence else "none"
        return {
            "state": state,
            "lean": lean,
            "same_confidence": round(same.confidence, 4),
            "split_confidence": round(split.confidence, 4),
            "unresolved_events": [list(e.interval_ms) + [e.cue] for e in events if e.verdict == "UNRESOLVED"],
            "split_events": [list(e.interval_ms) + [e.cue] for e in events if e.verdict == "SPLIT"],
            "blips": [list(e.interval_ms) + [e.cue] for e in events if e.verdict == "BLIP"],
            "label": "SOFT",
        }


