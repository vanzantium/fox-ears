class CueExtractor:
    """
    Extracts continuity evidence between consecutive EAR MEASUREMENTS.

    It deliberately does not decide which cue should dominate.

    P0 2026-11-15:
    - spectral continuity is UNAVAILABLE when either frame is silent (a cosine of
      zero against silence is not a spectral break);
    - binaural trajectory uses interaural level difference in dB (ILD, per band,
      broadband fallback) and ITD as separate measures, each with availability;
    - temporal contour adds a per-band envelope-pattern measure (does this frame
      continue the band's own recent level pattern?) next to the gross level
      change, so a contour phase change or exchange is visible.
    """

    @staticmethod
    def _silent(f: EarFrame) -> bool:
        return f.left_level < SILENCE_LEVEL and f.right_level < SILENCE_LEVEL

    @staticmethod
    def _unavailable(cue: str, a: EarFrame, b: EarFrame, reason: str, **extra: Any) -> CueEvidence:
        return CueEvidence(cue, f"t={a.t_ms}", f"t={b.t_ms}", 0.5, 0.0,
                           {"reason": reason, **extra}, "UNAVAILABLE")

    def spectral(self, a: EarFrame, b: EarFrame) -> CueEvidence:
        if self._silent(a) or self._silent(b):
            return self._unavailable("spectral", a, b, "silent frame: spectral continuity not measurable",
                                     silence_a=self._silent(a), silence_b=self._silent(b))
        va = []
        vb = []
        for band in BANDS_HZ:
            va += [a.left_bands.get(band, 0.0), a.right_bands.get(band, 0.0)]
            vb += [b.left_bands.get(band, 0.0), b.right_bands.get(band, 0.0)]
        sim = cosine_similarity(va, vb)
        return CueEvidence(
            "spectral",
            f"t={a.t_ms}",
            f"t={b.t_ms}",
            sim,
            1.0 - sim,
            {"cosine_similarity": round(sim, 6)},
        )

    @staticmethod
    def _band_db(f: EarFrame, band: int) -> Optional[float]:
        lvl = (f.left_bands.get(band, 0.0) + f.right_bands.get(band, 0.0)) / 2.0
        return 20.0 * math.log10(lvl) if lvl > BAND_EPS else None

    def _pattern(self, ref: Optional[EarFrame], prev: Optional[EarFrame], a: EarFrame, b: EarFrame) -> Optional[float]:
        """
        Per-band envelope pattern continuity of b. Predictors: period-2 (b ~ prev,
        covers steady and alternating envelopes) and linear (b ~ 2a - prev).
        Returns None when no band has energy in all compared frames.
        """
        if prev is None:
            return None
        devs = []
        wts = []
        for band in BANDS_HZ:
            dp, da, db = self._band_db(prev, band), self._band_db(a, band), self._band_db(b, band)
            if dp is None or da is None or db is None:
                continue
            dev = min(abs(db - dp), abs(db - (2 * da - dp)))
            devs.append(dev)
            wts.append(10 ** (db / 20.0))
        if not devs:
            return None
        dev = sum(d * w for d, w in zip(devs, wts)) / sum(wts)
        return clamp(1.0 - dev / CONTOUR_PATTERN_DB)

    def temporal_contour(self, a: EarFrame, b: EarFrame, prev: Optional[EarFrame] = None) -> CueEvidence:
        # Gross amplitude contour continuity: compare total bilateral level change.
        total_a = (a.left_level + a.right_level) / 2.0
        total_b = (b.left_level + b.right_level) / 2.0
        level_sim = normalized_similarity(total_a, total_b, scale=0.12)
        pattern_sim = self._pattern(None, prev, a, b)
        sim = level_sim if pattern_sim is None else min(level_sim, pattern_sim)
        return CueEvidence(
            "temporal_contour",
            f"t={a.t_ms}",
            f"t={b.t_ms}",
            sim,
            1.0 - sim,
            {
                "mean_level_a": round(total_a, 6),
                "mean_level_b": round(total_b, 6),
                "absolute_change": round(abs(total_b-total_a), 6),
                "level_continuity": round(level_sim, 6),
                "pattern_continuity": None if pattern_sim is None else round(pattern_sim, 6),
            },
        )

    def onset_offset(self, a: EarFrame, b: EarFrame) -> CueEvidence:
        silence_a = self._silent(a)
        silence_b = self._silent(b)
        new_onset = max(b.left_onset, b.right_onset)
        if silence_a != silence_b:
            continuity = 0.15
        elif new_onset >= 0.12 and not silence_b:
            continuity = 0.25
        else:
            continuity = 0.95
        return CueEvidence(
            "onset_offset",
            f"t={a.t_ms}",
            f"t={b.t_ms}",
            continuity,
            1.0 - continuity,
            {
                "silence_a": silence_a,
                "silence_b": silence_b,
                "new_onset_b": round(new_onset, 6),
            },
        )

    @staticmethod
    def _ild_db(f: EarFrame) -> Dict[str, float]:
        """ILD (L/R, dB) per band with energy in both ears, plus broadband."""
        out: Dict[str, float] = {}
        for band in BANDS_HZ:
            l, r = f.left_bands.get(band, 0.0), f.right_bands.get(band, 0.0)
            if l > BAND_EPS and r > BAND_EPS:
                out[str(band)] = 20.0 * math.log10(l / r)
        if f.left_level > BAND_EPS and f.right_level > BAND_EPS:
            out["broadband"] = 20.0 * math.log10(f.left_level / f.right_level)
        return out

    def binaural_trajectory(self, a: EarFrame, b: EarFrame) -> CueEvidence:
        ia, ib = self._ild_db(a), self._ild_db(b)
        shared = [k for k in ia if k in ib and k != "broadband"]
        if shared:
            wa = {k: a.left_bands.get(int(k), 0.0) + a.right_bands.get(int(k), 0.0)
                     + b.left_bands.get(int(k), 0.0) + b.right_bands.get(int(k), 0.0) for k in shared}
            ild_change = sum(abs(ib[k] - ia[k]) * wa[k] for k in shared) / sum(wa.values())
            ild_basis = "per-band"
        elif "broadband" in ia and "broadband" in ib:
            ild_change = abs(ib["broadband"] - ia["broadband"])
            ild_basis = "broadband (no band shared by both frames)"
        else:
            ild_change = None
            ild_basis = "unavailable"
        ild_sim = None if ild_change is None else clamp(1.0 - ild_change / ILD_SCALE_DB)

        if a.itd_ms_r_minus_l is not None and b.itd_ms_r_minus_l is not None:
            itd_sim = normalized_similarity(a.itd_ms_r_minus_l, b.itd_ms_r_minus_l, scale=ITD_SCALE_MS)
        else:
            itd_sim = None

        evidence = {
            "ild_db_a": {k: round(v, 4) for k, v in ia.items()},
            "ild_db_b": {k: round(v, 4) for k, v in ib.items()},
            "ild_change_db": None if ild_change is None else round(ild_change, 4),
            "ild_basis": ild_basis,
            "ild_continuity": None if ild_sim is None else round(ild_sim, 6),
            "ild_availability": "UNAVAILABLE" if ild_sim is None else "AVAILABLE",
            "itd_ms_a": a.itd_ms_r_minus_l,
            "itd_ms_b": b.itd_ms_r_minus_l,
            "itd_continuity": None if itd_sim is None else round(itd_sim, 6),
            "itd_availability": "UNAVAILABLE" if itd_sim is None else "AVAILABLE",
        }
        subs = [x for x in (ild_sim, itd_sim) if x is not None]
        if not subs:
            return self._unavailable("binaural_trajectory", a, b, "no interaural level or time measurement", **evidence)
        # A jump in either measure is a spatial jump; disagreement is logged, not averaged away.
        sim = min(subs)
        if len(subs) == 2:
            evidence["ild_itd_disagree"] = abs(subs[0] - subs[1]) > 0.4
        return CueEvidence("binaural_trajectory", f"t={a.t_ms}", f"t={b.t_ms}", sim, 1.0 - sim, evidence)

    def interval(self, a: EarFrame, b: EarFrame, prev: Optional[EarFrame] = None) -> CueConflictLedger:
        cues = [
            self.spectral(a,b),
            self.temporal_contour(a,b,prev),
            self.onset_offset(a,b),
            self.binaural_trajectory(a,b),
        ]

        # "Strong continuity" vs "strong discontinuity" contradiction, available cues only.
        live = [c for c in cues if c.availability == "AVAILABLE"]
        supporting = [c.cue_type for c in live if c.continuity >= STRONG_CONT]
        opposing = [c.cue_type for c in live if c.continuity <= 0.35]
        contradictions = [(s,o) for s in supporting for o in opposing]
        return CueConflictLedger(a.t_ms, b.t_ms, cues, contradictions)

    def series(self, frames: Sequence[EarFrame]) -> List[CueConflictLedger]:
        return [self.interval(a, b, frames[i-1] if i > 0 else None)
                for i, (a, b) in enumerate(zip(frames, frames[1:]))]

    def bridge(self, cue: str, frames: Sequence[EarFrame], pre: int, post: int) -> Optional[float]:
        """
        Continuity of one cue between the frame before a break (pre) and a frame
        after it (post). Used for persistence / recovery: if post matches pre, the
        break was a there-and-back blip; if not, the change persisted.
        """
        a, b = frames[pre], frames[post]
        if cue == "spectral":
            c = self.spectral(a, b)
        elif cue == "onset_offset":
            c = self.onset_offset(a, b)
        elif cue == "binaural_trajectory":
            # Trajectory bridge: extrapolate each band's ILD from (pre-1 -> pre) to
            # post, so a source that keeps moving across a gap still bridges,
            # while a teleport does not.
            if pre >= 1:
                i0, i1, i2 = self._ild_db(frames[pre - 1]), self._ild_db(a), self._ild_db(b)
                keys = [k for k in i1 if k in i0 and k in i2 and k != "broadband"] or \
                       [k for k in ("broadband",) if k in i0 and k in i1 and k in i2]
                if keys:
                    steps = post - pre
                    dev = sum(abs(i2[k] - (i1[k] + steps * (i1[k] - i0[k]))) for k in keys) / len(keys)
                    return clamp(1.0 - dev / ILD_SCALE_DB)
            c = self.binaural_trajectory(a, b)
        else:
            level = normalized_similarity((a.left_level + a.right_level) / 2.0,
                                          (b.left_level + b.right_level) / 2.0, scale=0.12)
            # Envelope pattern: compare post with the latest frame <= pre of the same
            # parity (period-2 predictor), so alternating envelopes bridge correctly.
            r = post - 2
            while r > pre:
                r -= 2
            pat = None
            if r >= 0:
                devs = []
                for band in BANDS_HZ:
                    dr, db = self._band_db(frames[r], band), self._band_db(b, band)
                    if dr is not None and db is not None:
                        devs.append(abs(db - dr))
                if devs:
                    pat = clamp(1.0 - (sum(devs) / len(devs)) / CONTOUR_PATTERN_DB)
            return level if pat is None else min(level, pat)
        return None if c.availability != "AVAILABLE" else c.continuity


