@dataclass(frozen=True)
class WorldTruthEvent:
    """
    Simulator-only record. Never emitted to blind receivers.
    """
    trial_id: str
    intended_manipulation: str
    hidden_histories: List[str]
    notes: str = ""


@dataclass(frozen=True)
class EarFrame:
    t_ms: int
    left_level: float
    right_level: float
    left_bands: Dict[int, float]
    right_bands: Dict[int, float]
    left_onset: float = 0.0
    right_onset: float = 0.0
    itd_ms_r_minus_l: Optional[float] = None

    def blind_dict(self) -> Dict[str, Any]:
        return {
            "t_ms": self.t_ms,
            "left_ear": {
                "level": round(self.left_level, 6),
                "bands": {str(k): round(v, 6) for k, v in self.left_bands.items()},
                "onset": round(self.left_onset, 6),
            },
            "right_ear": {
                "level": round(self.right_level, 6),
                "bands": {str(k): round(v, 6) for k, v in self.right_bands.items()},
                "onset": round(self.right_onset, 6),
            },
            "binaural_measurement": {
                "level_delta_L_minus_R": round(self.left_level - self.right_level, 6),
                "itd_ms_R_minus_L": None if self.itd_ms_r_minus_l is None else round(self.itd_ms_r_minus_l, 6),
            },
        }


@dataclass(frozen=True)
class CueEvidence:
    cue_type: str
    observation_a: str
    observation_b: str
    continuity: float
    conflict: float
    evidence: Dict[str, Any]

    def __post_init__(self):
        if self.cue_type not in CUE_TYPES:
            raise ValueError(f"unknown cue_type {self.cue_type}")
        if not 0.0 <= self.continuity <= 1.0:
            raise ValueError("continuity must be in [0,1]")
        if not 0.0 <= self.conflict <= 1.0:
            raise ValueError("conflict must be in [0,1]")


@dataclass
class CueConflictLedger:
    interval_a_ms: int
    interval_b_ms: int
    cues: List[CueEvidence]
    contradiction_pairs: List[Tuple[str, str]] = field(default_factory=list)

    @property
    def has_conflict(self) -> bool:
        return bool(self.contradiction_pairs)


@dataclass
class BindingHypothesis:
    hypothesis_id: str
    observations: List[str]
    supporting_cues: List[str]
    opposing_cues: List[str]
    confidence: float
    status: str  # candidate / preferred / unresolved
    rationale: str

    def __post_init__(self):
        if self.status not in {"candidate", "preferred", "unresolved"}:
            raise ValueError("invalid hypothesis status")
        self.confidence = clamp(self.confidence)


@dataclass
class BindingLedger:
    trial_id: str
    hypotheses: List[BindingHypothesis]
    conflict_intervals: List[Tuple[int, int]]
    note: str = "Hypotheses are model-side scaffolding; blind calibration may omit them."


