# Hypothesis generation
# ---------------------------------------------------------------------

class HypothesisBuilder:
    """
    Produces competing histories from cue ledgers without encoding a learned
    perceptual cue hierarchy.

    Confidence is evidence-balance, not "correctness".
    """

    def build(self, trial_id: str, ledgers: Sequence[CueConflictLedger]) -> BindingLedger:
        if not ledgers:
            return BindingLedger(trial_id, [], [])

        cue_means = {cue: [] for cue in CUE_TYPES}
        for ledger in ledgers:
            for c in ledger.cues:
                cue_means[c.cue_type].append(c.continuity)
        means = {k: sum(v)/len(v) if v else 0.5 for k,v in cue_means.items()}

        same_support = [k for k,v in means.items() if v >= 0.65]
        same_oppose = [k for k,v in means.items() if v <= 0.45]
        same_conf = clamp((sum(means[k] for k in same_support) + 0.5) / (len(same_support)+1))

        split_support = [k for k,v in means.items() if v <= 0.45]
        split_oppose = [k for k,v in means.items() if v >= 0.65]
        split_conf = clamp((sum(1.0-means[k] for k in split_support) + 0.5) / (len(split_support)+1))

        conflicts = [(l.interval_a_ms,l.interval_b_ms) for l in ledgers if l.has_conflict]

        # If both histories have meaningful support, preserve unresolved competitors.
        if same_support and split_support:
            statuses = ("unresolved","unresolved")
        elif same_conf > split_conf:
            statuses = ("preferred","candidate")
        elif split_conf > same_conf:
            statuses = ("candidate","preferred")
        else:
            statuses = ("unresolved","unresolved")

        hypotheses = [
            BindingHypothesis(
                f"{trial_id}:H_SAME",
                ["observations may belong to one continuing sound-thing"],
                same_support,
                same_oppose,
                same_conf,
                statuses[0],
                "continuity cues support one-history binding; conflicting cues remain explicit",
            ),
            BindingHypothesis(
                f"{trial_id}:H_SPLIT",
                ["a new sound-thing may appear at one or more discontinuities"],
                split_support,
                split_oppose,
                split_conf,
                statuses[1],
                "discontinuity cues support split/history-reset binding; continuity cues remain explicit",
            ),
        ]
        return BindingLedger(trial_id, hypotheses, conflicts)


# ---------------------------------------------------------------------
# Runtime
# ---------------------------------------------------------------------

class FoxEarsBindingGrammar:
    def __init__(self):
        self.extractor = CueExtractor()
        self.hypotheses = HypothesisBuilder()

    def analyze(self, trial_id: str, frames: Sequence[EarFrame]) -> Dict[str, Any]:
        cue_ledgers = self.extractor.series(frames)
        binding = self.hypotheses.build(trial_id, cue_ledgers)
        return {
            "trial_id": trial_id,
            "ear_measurement": [f.blind_dict() for f in frames],
            "cue_evidence": [
                {
                    "interval": [l.interval_a_ms, l.interval_b_ms],
                    "cues": [asdict(c) for c in l.cues],
                    "contradiction_pairs": [list(x) for x in l.contradiction_pairs],
                }
                for l in cue_ledgers
            ],
            "binding_hypotheses": [asdict(h) for h in binding.hypotheses],
            "conflict_intervals": [list(x) for x in binding.conflict_intervals],
        }

    @staticmethod
    def blind_receipt(trial_id: str, frames: Sequence[EarFrame]) -> Dict[str, Any]:
        # Strict blind path: EAR MEASUREMENT ONLY.
        return {
            "trial_id": trial_id,
            "frames": [f.blind_dict() for f in frames],
        }


